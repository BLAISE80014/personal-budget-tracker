export function translate(text, language) {
  if (language !== 'Kinyarwanda' || typeof text !== 'string') return text
  if (kinyarwandaTranslations[text]) return kinyarwandaTranslations[text]
  const dynamicLabels = [
    [/^Notifications, (\d+) unread$/, (_, count) => `Ubutumwa bw’imenyesha ${count} butarasomwa`],
    [/^(View|Edit|Delete|Complete) (.+)$/, (_, action, subject) => `${{ View: 'Reba', Edit: 'Hindura', Delete: 'Siba', Complete: 'Rangiza' }[action]} ${subject}`],
    [/^Change role for (.+)$/, (_, subject) => `Hindura inshingano za ${subject}`],
    [/^(.+) income of (.+) was (updated|added|removed)\.$/, (_, source, amount, action) => `${source}: amafaranga winjije angana na ${amount} ${{ updated: 'yavuguruwe', added: 'yongeweho', removed: 'yakuweho' }[action]}.`],
    [/^(.+) expense of (.+) was (updated|added|removed)\.$/, (_, description, amount, action) => `${description}: ikiguzi kingana na ${amount} ${{ updated: 'cyavuguruwe', added: 'cyongeweho', removed: 'cyakuweho' }[action]}.`],
    [/^(.+) is (?:already )?(\d+)% used\.$/, (_, category, percent) => `Icyiciro ${category} cyakoreshejweho ${percent}%.`],
    [/^(.+) budget of (.+) was (updated|added|removed)\.$/, (_, category, amount, action) => `Ingengo y’imari ya ${category} ingana na ${amount} ${{ updated: 'yavuguruwe', added: 'yongeweho', removed: 'yakuweho' }[action]}.`],
    [/^The “(.+)” category was removed\.$/, (_, category) => `Icyiciro “${category}” cyakuweho.`],
    [/^Your (.+) savings goal was (updated|added|removed)\.$/, (_, goal, action) => `Intego yawe yo kuzigama ${goal} ${{ updated: 'yavuguruwe', added: 'yongeweho', removed: 'yakuweho' }[action]}.`],
  ]
  for (const [pattern, replacement] of dynamicLabels) {
    if (pattern.test(text)) return text.replace(pattern, replacement)
  }
  return text
}
