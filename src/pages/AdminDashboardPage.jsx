function formatDate(value) {
  if (!value) return '—'
  const parsed = new Date(value)
  return Number.isNaN(parsed.getTime()) ? String(value) : new Intl.DateTimeFormat(undefined, { dateStyle: 'medium' }).format(parsed)
}

function currency(value, currencyCode) {
  return new Intl.NumberFormat(undefined, { style: 'currency', currency: currencyCode, maximumFractionDigits: 0 }).format(Number(value) || 0)
}

function metricPath(values, width, height, padding = 8) {
  if (!values.length) return ''
  const max = Math.max(1, ...values)
  const min = Math.min(0, ...values)
  const spread = Math.max(1, max - min)
  return values.map((value, index) => {
    const x = padding + index * ((width - padding * 2) / Math.max(1, values.length - 1))
    const y = height - padding - ((value - min) / spread) * (height - padding * 2)
    return `${index ? 'L' : 'M'}${x},${y}`
  }).join(' ')
}

function TrendChart({ series, currencyCode }) {
  const width = 760
  const height = 220
  const userPath = metricPath(series.map((point) => point.users), width, height)
  const activityMax = Math.max(1, ...series.map((point) => point.transactions))
  const activityPath = metricPath(series.map((point) => (point.transactions / activityMax) * 100), width, height)
  const incomeValues = series.map((point) => point.income)
  const expenseValues = series.map((point) => point.expenses)
  const moneyMax = Math.max(1, ...incomeValues, ...expenseValues)
  const moneyPath = (values) => metricPath(values.map((value) => (value / moneyMax) * 100), width, height)

  if (!series.length || series.every((point) => !point.users && !point.income && !point.expenses)) {
    return <div className="admin-chart-empty">There is no activity in this date range yet.</div>
  }
  return (
    <div className="admin-chart-wrap">
      <div className="admin-chart-legend">
        <span><i className="users-legend" /> New users</span>
        <span><i className="activity-legend" /> Transactions</span>
        <span><i className="income-legend" /> Income ({currencyCode})</span>
        <span><i className="expense-legend" /> Expenses ({currencyCode})</span>
      </div>
      <svg className="admin-trend-chart" viewBox={`0 0 ${width} ${height}`} role="img" aria-label="User registrations, income, and expense activity over the selected period">
        {[0, 1, 2, 3].map((line) => <line key={line} x1="0" x2={width} y1={line * (height / 3)} y2={line * (height / 3)} className="admin-chart-gridline" />)}
        <path d={userPath} className="admin-chart-line users-line" />
        <path d={activityPath} className="admin-chart-line activity-line" />
        <path d={moneyPath(incomeValues)} className="admin-chart-line income-line" />
        <path d={moneyPath(expenseValues)} className="admin-chart-line expense-line" />
      </svg>
      <div className="admin-chart-range-labels">
        <span>{series[0]?.period || ''}</span>
        <span>{series[Math.floor((series.length - 1) / 2)]?.period || ''}</span>
        <span>{series[series.length - 1]?.period || ''}</span>
      </div>
      <span className="admin-chart-note">Each measure is scaled independently to show its trend.</span>
    </div>
  )
}

function CategoryBars({ title, rows, currencyCode }) {
  const max = Math.max(1, ...rows.map((row) => row.total))
  return (
    <section className="admin-panel admin-category-panel">
      <div className="admin-panel-heading"><div><h2>{title}</h2><p>Highest totals in recorded data</p></div><Tags size={17} /></div>
      {!rows.length && <p className="admin-empty">No category data is available yet.</p>}
      {rows.map((row) => (
        <div className="admin-category-row" key={row.name}>
          <div><span>{row.name}</span><strong>{currency(row.total, currencyCode)}</strong></div>
          <div className="admin-category-track"><i style={{ width: `${Math.max(2, (row.total / max) * 100)}%` }} /></div>
        </div>
      ))}
    </section>
  )
}

function Pagination({ page, pages, onPageChange }) {
  if (pages <= 1) return null
  return (
    <div className="admin-pagination">
      <span>Page {page} of {pages}</span>
      <div>
        <button type="button" aria-label="Previous page" disabled={page <= 1} onClick={() => onPageChange(page - 1)}><ChevronLeft size={17} /></button>
        <button type="button" aria-label="Next page" disabled={page >= pages} onClick={() => onPageChange(page + 1)}><ChevronRight size={17} /></button>
      </div>
    </div>
  )
}

function downloadCsv(records, filename) {
  const columns = [...new Set(records.flatMap((record) => Object.keys(record)))]
  const escapeCell = (value) => {
    const text = value == null ? '' : typeof value === 'object' ? JSON.stringify(value) : String(value)
    return `"${(/^[=+\-@]/.test(text) ? `'${text}` : text).replaceAll('"', '""')}"`
  }
  const csv = [columns.map(escapeCell).join(','), ...records.map((record) => columns.map((column) => escapeCell(record[column])).join(','))].join('\r\n')
  const url = URL.createObjectURL(new Blob([csv], { type: 'text/csv;charset=utf-8' }))
  const anchor = document.createElement('a')
  anchor.href = url
  anchor.download = filename
  anchor.click()
  window.setTimeout(() => URL.revokeObjectURL(url), 1000)
}

