                return <tr key={`${record.recordType}-${record.id}`}><td><strong>{title}</strong><small>{record.note || record.status || record.recordType}</small></td><td>{record.owner?.name || 'Account unavailable'}<small>{record.owner?.email || ''}</small></td><td><span className={`admin-record-type ${record.recordType}`}>{record.recordType}</span></td><td>{category}</td><td>{amount}</td><td>{record.month || formatDate(record.date || record.createdAt)}</td></tr>
